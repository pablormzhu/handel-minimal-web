export function productImage(input: { name: string; description?: string; sku?: string }): string {
  const brandBatch234 = input.sku ? BRAND_BATCH_234_SKU_IMAGES[input.sku] : undefined;
  if (brandBatch234) return brandBatch234;
  const brandBatch = input.sku ? BRAND_BATCH_SKU_IMAGES[input.sku] : undefined;
  if (brandBatch) return brandBatch;
  const verifiedOriginal = input.sku ? VERIFIED_ORIGINAL_SKU_IMAGES[input.sku] : undefined;
  if (verifiedOriginal) return verifiedOriginal;
  const reconstructedVerified = input.sku
    ? RECONSTRUCTED_VERIFIED_SKU_IMAGES[input.sku]
    : undefined;
  if (reconstructedVerified) return reconstructedVerified;
  const approvedLabeled = input.sku ? APPROVED_LABELED_SKU_IMAGES[input.sku] : undefined;
  if (approvedLabeled) return approvedLabeled;
  const refreshed = input.sku ? REFRESHED_SKU_IMAGES[input.sku] : undefined;
  if (refreshed) return refreshed;
  const verified = input.sku ? VERIFIED_CURRENT_SKU_IMAGES[input.sku] : undefined;
  if (verified) return verified;
  const ai = input.sku ? AI_IMAGES[input.sku] : undefined;
  if (ai) return ai;
  const real = input.sku ? SKU_IMAGES[input.sku] : undefined;
  if (real) return real;
  const text = `${input.name} ${input.description ?? ""}`;
  for (const [re, img] of RULES) {
    if (re.test(text)) return img;
  }
  return general;
}

